/**
 * 全屏电影预览的时间轴：60 秒，看点在古城本身——
 * 盘门起手，北上北寺塔，转拙政园、狮子林，收在双塔，
 * 最后拉高到天幕俯瞰整座沙盘。
 *
 * 相机与注视点各一条关键点序列，引擎逐段用 Catmull-Rom 插值（按弧长采样），
 * 段与段之间共享端点，因此全程没有硬切。
 */
export type TourTime = 'day' | 'night';

type Vec3 = readonly [number, number, number];

export interface TourShot {
  /** 段落时长（秒） */
  duration: number;
  /** 底部题字 */
  caption: string;
  /** 相机关键点（段内 Catmull-Rom） */
  camera: readonly Vec3[];
  /** 注视点关键点，与相机点一一对应 */
  target: readonly Vec3[];
  /** 段落起止 FOV */
  fov: readonly [number, number];
  /** 进入该段时切换昼夜（预留） */
  time?: TourTime;
}

